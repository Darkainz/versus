import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { homeSlots, products } from "../src/data/catalog";

const outputDirectory = resolve(process.cwd(), "supabase", "seeds");
const sqlText = (value: string) => `'${value.replaceAll("'", "''")}'`;
const nullableText = (value: string | null | undefined) =>
  value == null ? "null" : sqlText(value);
const sqlArray = (values: readonly string[]) => `array[${values.map(sqlText).join(", ")}]::text[]`;
const sqlNumber = (value: number | null | undefined) => (value == null ? "null" : String(value));
const sqlBoolean = (value: boolean) => (value ? "true" : "false");

const productColumns = [
  "id",
  "code",
  "slug",
  "brand_slug",
  "category_slug",
  "name",
  "tagline",
  "description",
  "visual_kind",
  "release_date",
  "new_until",
  "warranty_months",
  "compat",
  "is_active",
];

const productRows = products.map((product) =>
  [
    sqlText(product.id),
    sqlText(product.code),
    sqlText(product.slug),
    sqlText(product.brand_slug),
    sqlText(product.category_slug),
    sqlText(product.name),
    sqlText(product.tagline),
    sqlText(product.description),
    sqlText(product.visual_kind),
    sqlText(product.release_date),
    nullableText(product.new_until),
    String(product.warranty_months),
    sqlArray(product.compat as readonly string[]),
    "false",
  ].join(", "),
);

const productUpdates = productColumns
  .filter((column) => column !== "id" && column !== "code")
  .map((column) => `${column} = excluded.${column}`)
  .join(",\n    ");

const variantColumns = [
  "product_id",
  "sku",
  "color_name",
  "color_slug",
  "color_hex",
  "storage_gb",
  "size_mm",
  "price_fcfa",
  "stock",
  "low_stock_threshold",
  "is_default",
  "is_active",
  "position",
];

const variantRows = products.flatMap((product) =>
  product.variants.map((variant) =>
    [
      sqlText(product.id),
      sqlText(variant.sku),
      sqlText(variant.color_name),
      sqlText(variant.color_slug),
      nullableText(variant.color_hex?.toUpperCase()),
      sqlNumber(variant.storage_gb),
      sqlNumber(variant.size_mm),
      String(variant.price_fcfa),
      String(variant.stock),
      String(variant.low_stock_threshold),
      sqlBoolean(variant.is_default),
      sqlBoolean(variant.is_active),
      String(variant.position),
    ].join(", "),
  ),
);

const variantUpdates = variantColumns
  .filter((column) => column !== "sku")
  .map((column) => `${column} = excluded.${column}`)
  .join(",\n    ");

const specColumns = [
  "product_id",
  "screen_size_in",
  "screen_tech",
  "refresh_hz",
  "chip",
  "battery_mah",
  "autonomy_hours",
  "charging_w",
  "main_camera_mp",
  "weight_g",
  "ip_rating",
  "has_5g",
  "has_anc",
  "specs_note",
];

const specRows = products.map((product) =>
  [
    sqlText(product.id),
    sqlNumber(product.specs.screen_size_in),
    nullableText(product.specs.screen_tech),
    sqlNumber(product.specs.refresh_hz),
    nullableText(product.specs.chip),
    sqlNumber(product.specs.battery_mah),
    sqlNumber(product.specs.autonomy_hours),
    sqlNumber(product.specs.charging_w),
    sqlNumber(product.specs.main_camera_mp),
    sqlNumber(product.specs.weight_g),
    nullableText(product.specs.ip_rating),
    product.specs.has_5g == null ? "null" : sqlBoolean(product.specs.has_5g),
    product.specs.has_anc == null ? "null" : sqlBoolean(product.specs.has_anc),
    sqlText(product.specs.specs_note),
  ].join(", "),
);

const ids = products.map(({ id }) => sqlText(id)).join(", ");
const catalogSeed = `-- Generated by npm run db:seed:gen from src/data/catalog.ts.
insert into public.products (${productColumns.join(", ")})
values
  ${productRows.map((row) => `(${row})`).join(",\n  ")}
on conflict (code) do update
set ${productUpdates};

insert into public.product_variants (${variantColumns.join(", ")})
values
  ${variantRows.map((row) => `(${row})`).join(",\n  ")}
on conflict (sku) do update
set ${variantUpdates};

delete from public.product_images
where product_id in (${ids});

insert into public.product_images (
  product_id, color_slug, src, width, height, alt, is_primary, position
)
values
${products
  .filter((product) => product.image_src)
  .map(
    (product) =>
      `  (${sqlText(product.id)}, null, ${nullableText(product.image_src)}, ${sqlNumber(product.image_width)}, ${sqlNumber(product.image_height)}, ${nullableText(product.image_alt)}, true, 0)`,
  )
  .join(",\n")};

insert into public.product_specs (${specColumns.join(", ")})
values
  ${specRows.map((row) => `(${row})`).join(",\n  ")}
on conflict (product_id) do update
set ${specColumns
  .filter((column) => column !== "product_id")
  .map((column) => `${column} = excluded.${column}`)
  .join(",\n    ")};

update public.products
set is_active = true
where id in (${ids});
`;

const homeSeed = `-- Generated by npm run db:seed:gen from src/data/catalog.ts.
insert into public.home_slots (
  slot, position, product_id, theme_key, headline, subline, is_active
)
values
${homeSlots
  .map((entry) => {
    const product = products.find(({ code }) => code === entry.product_code);
    if (!product) {
      throw new Error(`Produit inconnu dans homeSlots : ${entry.product_code}`);
    }

    return `  (${sqlText(entry.slot)}, ${entry.position}, ${sqlText(product.id)}, ${sqlText(entry.theme_key)}, ${nullableText(entry.headline)}, ${nullableText(entry.subline)}, true)`;
  })
  .join(",\n")}
on conflict (slot, position) do update
set product_id = excluded.product_id,
    theme_key = excluded.theme_key,
    headline = excluded.headline,
    subline = excluded.subline,
    is_active = excluded.is_active;
`;

mkdirSync(outputDirectory, { recursive: true });
writeFileSync(resolve(outputDirectory, "20_catalog.sql"), catalogSeed, "utf8");
writeFileSync(resolve(outputDirectory, "30_home.sql"), homeSeed, "utf8");
